#!/usr/bin/env python3
"""
integrate_collections.py — merge every data/collections/<key>.json into the
shared catalog (data/texts.json, data/authors.json) and site/_redirects.

Idempotent. For each collection, rows whose id starts with the collection prefix
are replaced wholesale by the collection's current "texts" list (so entries removed
from a collection disappear from the catalog too).

Run by the integrator only (not by collection builders), before the build chain:
  integrate_collections -> build_reading_order -> render_verified -> build_index
  -> build_search -> build_quotes -> build_sitemap -> validate_strict -> audit_sections
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from collections_lib import ROOT, load_all  # noqa: E402

DATA = ROOT / "data" / "texts.json"
AUTHORS = ROOT / "data" / "authors.json"
REDIRECTS = ROOT / "site" / "_redirects"
MARK_START = "# --- collection redirects (generated by integrate_collections.py) ---"
MARK_END = "# --- end collection redirects ---"


def main():
    reg = load_all()
    texts = json.loads(DATA.read_text(encoding="utf-8"))
    authors = json.loads(AUTHORS.read_text(encoding="utf-8"))
    rows = texts["texts"]
    a_by_id = {a["id"]: a for a in authors["authors"]}
    redirects = []
    added = 0
    for key, d in reg.items():
        prefix = d["collection"]["prefix"]
        rows = [r for r in rows if not r["id"].startswith(prefix)]
        for r in d.get("texts", []):
            r = dict(r)
            r["collection"] = key
            rows.append(r)
            added += 1
        for a in d.get("authors", []):
            a_by_id[a["id"]] = {**a_by_id.get(a["id"], {}), **a}
        redirects += d.get("redirects", [])
    texts["texts"] = rows
    authors["authors"] = list(a_by_id.values())
    DATA.write_text(json.dumps(texts, indent=2, ensure_ascii=False), encoding="utf-8")
    AUTHORS.write_text(json.dumps(authors, indent=2, ensure_ascii=False), encoding="utf-8")

    existing = REDIRECTS.read_text(encoding="utf-8") if REDIRECTS.exists() else ""
    if MARK_START in existing:
        head, rest = existing.split(MARK_START, 1)
        tail = rest.split(MARK_END, 1)[1] if MARK_END in rest else ""
        existing = head.rstrip("\n") + "\n" + tail.lstrip("\n")
    block = "\n".join([MARK_START] + [f"{a} {b} 301" for a, b in redirects] + [MARK_END])
    if redirects:
        REDIRECTS.write_text((existing.rstrip("\n") + "\n\n" if existing.strip() else "") + block + "\n", encoding="utf-8")
    print(f"integrated {len(reg)} collections, {added} rows; catalog now {len(rows)} rows; {len(redirects)} redirects")


if __name__ == "__main__":
    main()
